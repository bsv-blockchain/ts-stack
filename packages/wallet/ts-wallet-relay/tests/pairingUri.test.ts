import { PrivateKey, ProtoWallet } from '@bsv/sdk'
import {
  buildPairingUri,
  DEFAULT_ACCEPTED_SCHEMAS,
  parsePairingUri,
  verifyPairingSignature
} from '../src/shared/pairingUri.js'
import { bytesToBase64url } from '../src/shared/encoding.js'
import { PROTOCOL_ID, type PairingParams } from '../src/types.js'
import {
  LOCAL_NETWORK_AUTHORITIES,
  LOOPBACK_AUTHORITIES,
  PUBLIC_AUTHORITIES
} from './fixtures/localDevelopmentHosts.js'

// A valid compressed secp256k1 public key (deterministic for tests)
const BACKEND_KEY = PrivateKey.fromRandom().toPublicKey().toString()

const VALID_BUILD_PARAMS = {
  sessionId: 'session-abc-123',
  backendIdentityKey: BACKEND_KEY,
  protocolID: JSON.stringify(PROTOCOL_ID),
  origin: 'https://app.example.com'
}

describe('buildPairingUri / parsePairingUri roundtrip', () => {
  it('builds a bsv-browser:// URI and parses it back to the original params', () => {
    const uri = buildPairingUri(VALID_BUILD_PARAMS)
    expect(uri).toMatch(/^bsv-browser:\/\//)

    const result = parsePairingUri(uri)
    expect(result.error).toBeNull()
    expect(result.params).not.toBeNull()

    const p = result.params!
    expect(p.topic).toBe('session-abc-123')
    expect(p.backendIdentityKey).toBe(BACKEND_KEY)
    expect(p.origin).toBe('https://app.example.com')
    expect(JSON.parse(p.protocolID)).toEqual(PROTOCOL_ID)
  })

  it('accepts a custom schema when passed in acceptedSchemas', () => {
    const uri = buildPairingUri({ ...VALID_BUILD_PARAMS, schema: 'my-app' })
    expect(parsePairingUri(uri, new Set(['my-app:'])).error).toBeNull()
    // rejected without the custom schema
    expect(parsePairingUri(uri).error).toBeTruthy()
  })

  it('relay URL is not embedded in the URI', () => {
    const uri = buildPairingUri(VALID_BUILD_PARAMS)
    expect(uri).not.toContain('relay=')
  })

  it('old QR codes with a relay param are accepted (relay is silently ignored)', () => {
    // Backward compat: QR codes generated by older versions included relay=…
    // The new parser must not reject them — it simply ignores the extra field.
    const base = buildPairingUri(VALID_BUILD_PARAMS)
    const uri = base + '&relay=wss%3A%2F%2Fold.example.com'
    const result = parsePairingUri(uri)
    expect(result.error).toBeNull()
    expect(result.params).not.toBeNull()
    // relay must not leak into params
    expect((result.params as unknown as Record<string, string>)['relay']).toBeUndefined()
  })

  it('expiry is in the future for a freshly built URI', () => {
    const uri = buildPairingUri(VALID_BUILD_PARAMS)
    const result = parsePairingUri(uri)
    expect(result.error).toBeNull()
    expect(Number(result.params!.expiry)).toBeGreaterThan(Date.now() / 1000)
  })

  it('respects custom pairingTtlMs', () => {
    const tenMinutes = 10 * 60 * 1000
    const uri = buildPairingUri({ ...VALID_BUILD_PARAMS, pairingTtlMs: tenMinutes })
    const result = parsePairingUri(uri)
    expect(result.error).toBeNull()
    // expiry should be roughly 10 min from now (allow ±5 s for test execution)
    const expiryMs = Number(result.params!.expiry) * 1000
    expect(expiryMs).toBeGreaterThan(Date.now() + tenMinutes - 5_000)
    expect(expiryMs).toBeLessThan(Date.now() + tenMinutes + 5_000)
  })

  it('sig field roundtrips through buildPairingUri / parsePairingUri', () => {
    const uri = buildPairingUri({ ...VALID_BUILD_PARAMS, sig: 'dGVzdA' })
    const result = parsePairingUri(uri)
    expect(result.error).toBeNull()
    expect(result.params!.sig).toBe('dGVzdA')
  })

  it('sig is absent when not passed to buildPairingUri', () => {
    const uri = buildPairingUri(VALID_BUILD_PARAMS)
    const result = parsePairingUri(uri)
    expect(result.params!.sig).toBeUndefined()
  })
})

describe('parsePairingUri validation', () => {
  it('rejects an unrecognised URI scheme', () => {
    const result = parsePairingUri('https://example.com/pair?foo=bar')
    expect(result.error).toBeTruthy()
    expect(result.params).toBeNull()
  })

  it('rejects a URI with missing required fields', () => {
    // Missing backendIdentityKey
    const uri = 'bsv-browser://pair?topic=abc&origin=https://app.example.com'
    const result = parsePairingUri(uri)
    expect(result.error).toBeTruthy()
  })

  it('rejects duplicate security fields and non-pair deep-link routes', () => {
    const base = buildPairingUri(VALID_BUILD_PARAMS)
    expect(parsePairingUri(`${base}&origin=https%3A%2F%2Fevil.example`).error).toMatch(/duplicate/)
    expect(parsePairingUri(base.replace('://pair?', '://other/pair?')).error).toMatch(
      /exact wallet.*route/
    )
    expect(parsePairingUri(`${base}#fragment`).error).toMatch(/exact wallet.*route/)
  })

  it('rejects an expired QR code', () => {
    const p = new URLSearchParams({
      topic: 'x',
      backendIdentityKey: BACKEND_KEY,
      protocolID: JSON.stringify(PROTOCOL_ID),
      origin: 'https://app.example.com',
      expiry: String(Math.floor(Date.now() / 1000) - 60) // 60 s in the past
    })
    const result = parsePairingUri(`bsv-browser://pair?${p}`)
    expect(result.error).toMatch(/expired/i)
  })

  it('rejects a malformed backendIdentityKey', () => {
    const p = new URLSearchParams({
      topic: 'x',
      backendIdentityKey: 'not-a-pubkey',
      protocolID: JSON.stringify(PROTOCOL_ID),
      origin: 'https://app.example.com',
      expiry: String(Math.floor(Date.now() / 1000) + 120)
    })
    const result = parsePairingUri(`bsv-browser://pair?${p}`)
    expect(result.error).toMatch(/public key/i)
  })

  it('rejects an origin that is not http:// or https://', () => {
    const p = new URLSearchParams({
      topic: 'x',
      backendIdentityKey: BACKEND_KEY,
      protocolID: JSON.stringify(PROTOCOL_ID),
      origin: 'ftp://app.example.com',
      expiry: String(Math.floor(Date.now() / 1000) + 120)
    })
    const result = parsePairingUri(`bsv-browser://pair?${p}`)
    expect(result.error).toMatch(/origin/i)
  })

  it('rejects remote HTTP origins but allows loopback development origins by default', () => {
    expect(() =>
      buildPairingUri({ ...VALID_BUILD_PARAMS, origin: 'http://app.example.com' })
    ).toThrow(/HTTPS/)
    const remoteUrl = new URL(buildPairingUri(VALID_BUILD_PARAMS))
    remoteUrl.searchParams.set('origin', 'http://app.example.com')
    const remote = remoteUrl.toString()
    expect(parsePairingUri(remote).error).toMatch(/HTTPS/)

    for (const authority of LOOPBACK_AUTHORITIES) {
      const origin = `http://${authority}`
      const parsed = parsePairingUri(buildPairingUri({ ...VALID_BUILD_PARAMS, origin }))
      expect(parsed.error).toBeNull()
      expect(parsed.params?.origin).toBe(origin)
    }
    for (const authority of PUBLIC_AUTHORITIES) {
      const origin = `http://${authority}`
      for (const allowLocalNetworkHttp of [false, true]) {
        expect(() =>
          buildPairingUri({ ...VALID_BUILD_PARAMS, origin, allowLocalNetworkHttp })
        ).toThrow('pairing origin must be HTTPS')
      }
      const forged = new URL(buildPairingUri(VALID_BUILD_PARAMS))
      forged.searchParams.set('origin', origin)
      expect(parsePairingUri(forged.toString()).error).toMatch(/HTTPS/)
      expect(
        parsePairingUri(forged.toString(), undefined, { allowLocalNetworkHttp: true }).error
      ).toBe('origin must be HTTPS, except for loopback or local-network development')
    }
  })

  it('accepts private-network HTTP origins only with allowLocalNetworkHttp', () => {
    for (const authority of LOCAL_NETWORK_AUTHORITIES) {
      const origin = `http://${authority}`
      expect(() => buildPairingUri({ ...VALID_BUILD_PARAMS, origin })).toThrow(
        'allowLocalNetworkHttp'
      )
      const uri = buildPairingUri({ ...VALID_BUILD_PARAMS, origin, allowLocalNetworkHttp: true })

      const rejected = parsePairingUri(uri)
      expect(rejected.params).toBeNull()
      // Phone-side errors reach wallet users, so they carry no developer hint.
      expect(rejected.error).toBe('origin must be HTTPS, except for loopback development')
      expect(parsePairingUri(uri, DEFAULT_ACCEPTED_SCHEMAS, {}).params).toBeNull()

      const accepted = parsePairingUri(uri, DEFAULT_ACCEPTED_SCHEMAS, {
        allowLocalNetworkHttp: true
      })
      expect(accepted.error).toBeNull()
      expect(accepted.params?.origin).toBe(origin)
    }
  })

  it('rejects a non-boolean allowLocalNetworkHttp', () => {
    const uri = buildPairingUri(VALID_BUILD_PARAMS)
    expect(
      parsePairingUri(uri, undefined, { allowLocalNetworkHttp: 'true' as unknown as boolean }).error
    ).toBe('allowLocalNetworkHttp must be a boolean')
    expect(() =>
      buildPairingUri({
        ...VALID_BUILD_PARAMS,
        allowLocalNetworkHttp: 1 as unknown as boolean
      })
    ).toThrow('allowLocalNetworkHttp must be a boolean')
  })
})

// ── Signature tests ───────────────────────────────────────────────────────────

describe('verifyPairingSignature', () => {
  let backendKey: PrivateKey
  let backendKeyHex: string
  let wallet: ProtoWallet

  beforeEach(() => {
    backendKey = PrivateKey.fromRandom()
    backendKeyHex = backendKey.toPublicKey().toString()
    wallet = new ProtoWallet(backendKey)
  })

  async function makeSignedParams(
    overrides?: Partial<{
      topic: string
      backendIdentityKey: string
      origin: string
      expiry: string
    }>
  ) {
    const topic = overrides?.topic ?? 'test-session-id'
    const bik = overrides?.backendIdentityKey ?? backendKeyHex
    const origin = overrides?.origin ?? 'https://app.example.com'
    const expiry = overrides?.expiry ?? String(Math.floor(Date.now() / 1000) + 120)

    const data = Array.from(new TextEncoder().encode(`${topic}|${bik}|${origin}|${expiry}`))
    const { signature } = await wallet.createSignature({
      data,
      protocolID: [0, 'qr pairing'],
      keyID: topic,
      counterparty: 'anyone'
    })
    const sig = bytesToBase64url(signature as number[])

    return {
      topic,
      backendIdentityKey: bik,
      protocolID: JSON.stringify(PROTOCOL_ID),
      origin,
      expiry,
      sig
    }
  }

  it('returns true for a valid signature', async () => {
    expect(await verifyPairingSignature(await makeSignedParams())).toBe(true)
  })

  it('rejects rather than throwing synchronously when params are missing', async () => {
    let result: Promise<boolean> | undefined
    expect(() => {
      result = verifyPairingSignature(null as unknown as PairingParams)
    }).not.toThrow()
    await expect(result).rejects.toThrow(TypeError)
  })

  it('returns false when backendIdentityKey is tampered', async () => {
    const params = await makeSignedParams()
    const otherKey = PrivateKey.fromRandom().toPublicKey().toString()
    expect(await verifyPairingSignature({ ...params, backendIdentityKey: otherKey })).toBe(false)
  })

  it('returns false when origin is tampered', async () => {
    const params = await makeSignedParams()
    expect(await verifyPairingSignature({ ...params, origin: 'https://evil.example.com' })).toBe(
      false
    )
  })

  it('returns false when expiry is tampered', async () => {
    const params = await makeSignedParams()
    expect(
      await verifyPairingSignature({ ...params, expiry: String(Number(params.expiry) + 9999) })
    ).toBe(false)
  })

  it('verifies a private-network HTTP origin only with allowLocalNetworkHttp', async () => {
    const params = await makeSignedParams({ origin: 'http://192.168.1.20:3000' })
    expect(await verifyPairingSignature(params)).toBe(false)
    expect(await verifyPairingSignature(params, { allowLocalNetworkHttp: false })).toBe(false)
    expect(await verifyPairingSignature(params, { allowLocalNetworkHttp: true })).toBe(true)
    const loopback = await makeSignedParams({ origin: 'http://127.0.0.1:3000' })
    expect(await verifyPairingSignature(loopback)).toBe(true)
  })

  it('returns false when sig is absent', async () => {
    const { sig: _sig, ...unsigned } = await makeSignedParams()
    expect(await verifyPairingSignature(unsigned)).toBe(false)
  })

  it('returns false for a corrupted sig string', async () => {
    const params = await makeSignedParams()
    expect(await verifyPairingSignature({ ...params, sig: 'AAAAAAAAAA' })).toBe(false)
  })

  it('buildPairingUri + parsePairingUri roundtrips the sig and verifies', async () => {
    const params = await makeSignedParams()
    const uri = buildPairingUri({
      sessionId: params.topic,
      backendIdentityKey: params.backendIdentityKey,
      protocolID: params.protocolID,
      origin: params.origin,
      expiry: Number(params.expiry),
      sig: params.sig
    })
    const result = parsePairingUri(uri)
    expect(result.error).toBeNull()
    expect(result.params!.sig).toBe(params.sig)
    expect(await verifyPairingSignature(result.params!)).toBe(true)
  })
})

// ── Performance tests ─────────────────────────────────────────────────────────

describe('QR signature performance', () => {
  const ITERATIONS = 20

  it(`createSignature: avg < 500 ms over ${ITERATIONS} iterations`, async () => {
    const key = PrivateKey.fromRandom()
    const wallet = new ProtoWallet(key)
    const bik = key.toPublicKey().toString()
    const topic = 'perf-session'
    const origin = 'https://app.example.com'

    const durations: number[] = []
    for (let i = 0; i < ITERATIONS; i++) {
      const expiry = Math.floor((Date.now() + 120_000) / 1000)
      const data = Array.from(new TextEncoder().encode(`${topic}|${bik}|${origin}|${expiry}`))
      const t0 = performance.now()
      await wallet.createSignature({
        data,
        protocolID: [0, 'qr pairing'],
        keyID: topic,
        counterparty: 'anyone'
      })
      durations.push(performance.now() - t0)
    }

    const avg = durations.reduce((a, b) => a + b, 0) / durations.length
    console.log(
      `createSignature avg=${avg.toFixed(2)}ms  min=${Math.min(...durations).toFixed(2)}ms  max=${Math.max(...durations).toFixed(2)}ms`
    )
    expect(avg).toBeLessThan(500)
  }, 30_000)

  it(`verifyPairingSignature: avg < 500 ms over ${ITERATIONS} iterations`, async () => {
    const key = PrivateKey.fromRandom()
    const wallet = new ProtoWallet(key)
    const bik = key.toPublicKey().toString()
    const topic = 'perf-session'
    const origin = 'https://app.example.com'
    const expiry = Math.floor((Date.now() + 120_000) / 1000)

    const data = Array.from(new TextEncoder().encode(`${topic}|${bik}|${origin}|${expiry}`))
    const { signature } = await wallet.createSignature({
      data,
      protocolID: [0, 'qr pairing'],
      keyID: topic,
      counterparty: 'anyone'
    })
    const sig = bytesToBase64url(signature as number[])
    const uri = buildPairingUri({
      sessionId: topic,
      backendIdentityKey: bik,
      protocolID: JSON.stringify(PROTOCOL_ID),
      origin,
      expiry,
      sig
    })
    const { params } = parsePairingUri(uri)

    const durations: number[] = []
    for (let i = 0; i < ITERATIONS; i++) {
      const t0 = performance.now()
      await verifyPairingSignature(params!)
      durations.push(performance.now() - t0)
    }

    const avg = durations.reduce((a, b) => a + b, 0) / durations.length
    console.log(
      `verifyPairingSignature avg=${avg.toFixed(2)}ms  min=${Math.min(...durations).toFixed(2)}ms  max=${Math.max(...durations).toFixed(2)}ms`
    )
    expect(avg).toBeLessThan(500)
  }, 30_000)
})
