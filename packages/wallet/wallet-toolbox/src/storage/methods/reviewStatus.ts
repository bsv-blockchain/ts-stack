import { StorageReqWrite } from '../StorageReqWrite'
import type { StorageStatusReviewArgs, StorageWriterAdmission } from '../StorageActiveWrite'
import { EntityProvenTxReq } from '../schema/entities/EntityProvenTxReq'
import { quarantineRecordedTerminalInputs } from './reconcileFailedTransactionInputs'
import { Knex } from 'knex'
import type { StorageKnex } from '../StorageKnex'
import { WalletError } from '../../sdk/WalletError'
import type { ProvenTxReqStatus } from '../../sdk/types'
import { TableTransaction } from '../schema/tables/TableTransaction'
import { TableOutput } from '../schema/tables/TableOutput'

const provenTxReqStatusesSafeForInputRestore: ProvenTxReqStatus[] = ['invalid', 'doubleSpend']

/**
 * Looks for unpropagated state:
 *
 * 1. set transactions to 'failed' if not already failed and provenTxReq with matching txid has status of 'invalid'.
 * 2. sets outputs to spendable true, spentBy undefined if spentBy is a terminal failed transaction.
 * 3. sets outputs generated by terminal failed transactions to spendable false, spentBy undefined.
 * 4. sets transactions to 'completed' if provenTx with matching txid exists and current provenTxId is null.
 *
 * @param storage
 * @param args
 * @returns
 */
async function reviewStatusLegacy(
  storage: StorageKnex,
  args: StorageStatusReviewArgs,
  scope?: { userId: number; transactionId: number; protectInputs?: boolean }
): Promise<{ log: string }> {
  const r: { log: string } = { log: '' }

  const runReviewStatusQuery = async (pq: ReviewStatusQuery): Promise<void> => {
    try {
      pq.sql = pq.q.toString()
      const count = await pq.q
      if (count > 0) {
        r.log += `${count} ${pq.log}\n`
      }
    } catch (error_: unknown) {
      // eslint-disable-next-line @typescript-eslint/no-unused-vars
      const e = WalletError.fromUnknown(error_)
      throw error_
    }
  }

  const k = storage.toDb(args.trx)

  const qs: ReviewStatusQuery[] = []

  qs.push(
    {
      log: "transactions updated to status of 'failed' where provenTxReq with matching txid is 'invalid'",
      /*
          UPDATE transactions SET status = 'failed'
          WHERE exists(select 1 from proven_tx_reqs as r where transactions.txid = r.txid and r.status = 'invalid')
          */
      q: k<TableTransaction>('transactions')
        .update({ status: 'failed' })
        .whereNot({ status: 'failed' })
        .whereExists(function () {
          this.select(k.raw(1))
            .from('proven_tx_reqs as r')
            .whereRaw('transactions.txid = r.txid')
            .whereIn('r.status', scope == null ? ['invalid'] : ['invalid', 'doubleSpend'])
        })
    },
    {
      log: 'outputs updated to spendable where spentBy is a failed transaction with no blocking ProvenTxReq',
      /*
          UPDATE outputs SET spentBy = null, spendable = 1
          where exists(select 1 from transactions as t where outputs.spentBy = t.transactionId and t.status = 'failed')
          and not exists(select 1 from proven_tx_reqs as r where r.txid = t.txid and r.status not in ('invalid', 'doubleSpend'))
          */
      q: k<TableOutput>('outputs')
        .update({ spentBy: null as unknown as undefined, spendable: true })
        .whereExists(function () {
          this.select(k.raw(1))
            .from('transactions as t')
            // ?? quotes identifiers: Postgres lowercases unquoted names, so camelCase columns must be quoted.
            .whereRaw("?? = ?? and t.status = 'failed'", ['outputs.spentBy', 't.transactionId'])
            .whereNotExists(function () {
              // A failed transaction can still be reconciled from active or valid reqs.
              // Only terminal failure reqs are safe for input restoration.
              this.select(k.raw(1))
                .from('proven_tx_reqs as r')
                .whereRaw('r.txid = t.txid')
                .whereNotIn('r.status', provenTxReqStatusesSafeForInputRestore)
            })
            .whereNotExists(function () {
              // Outputs generated by a failed transaction are not valid inputs to restore.
              this.select(k.raw(1))
                .from('transactions as source')
                .whereRaw("?? = ?? and source.status = 'failed'", ['outputs.transactionId', 'source.transactionId'])
            })
        })
    },
    {
      log: 'outputs updated to not spendable where generated by a failed transaction with no blocking ProvenTxReq',
      /*
          UPDATE outputs SET spentBy = null, spendable = 0
          where exists(select 1 from transactions as t where outputs.transactionId = t.transactionId and t.status = 'failed')
          and not exists(select 1 from proven_tx_reqs as r where r.txid = t.txid and r.status not in ('invalid', 'doubleSpend'))
          */
      q: k<TableOutput>('outputs')
        .update({ spentBy: null as unknown as undefined, spendable: false })
        .where(function () {
          this.where({ spendable: true }).orWhereNotNull('spentBy')
        })
        .whereExists(function () {
          this.select(k.raw(1))
            .from('transactions as t')
            // ?? quotes identifiers: Postgres lowercases unquoted names, so camelCase columns must be quoted.
            .whereRaw("?? = ?? and t.status = 'failed'", ['outputs.transactionId', 't.transactionId'])
            .whereNotExists(function () {
              // A failed transaction can still be reconciled from active or valid reqs.
              // Only terminal failure reqs are safe for output neutralization.
              this.select(k.raw(1))
                .from('proven_tx_reqs as r')
                .whereRaw('r.txid = t.txid')
                .whereNotIn('r.status', provenTxReqStatusesSafeForInputRestore)
            })
        })
    },
    {
      log: "transactions updated with provenTxId and status of 'completed' where provenTx with matching txid exists",
      /*
          UPDATE transactions SET status = 'completed', provenTxId = p.provenTxId
          FROM proven_txs p
          WHERE transactions.txid = p.txid AND transactions.provenTxId IS NULL
          */
      q: k<TableTransaction>('transactions')
        .update({
          status: 'completed',
          // ?? quotes identifiers: Postgres lowercases unquoted names, so camelCase columns must be quoted.
          provenTxId: k.raw('(SELECT ?? FROM proven_txs AS p WHERE transactions.txid = p.txid)', ['p.provenTxId'])
        })
        .whereNull('provenTxId')
        .whereExists(function () {
          this.select(k.raw(1)).from('proven_txs as p').whereRaw('transactions.txid = p.txid')
        })
    }
  )

  if (scope != null) {
    for (let i = 0; i < qs.length; i++) {
      qs[i].q.where('userId', scope.userId).where(i === 1 ? 'spentBy' : 'transactionId', scope.transactionId)
    }
    // An observed rejection is never stronger than a stored completed proof.
    qs[0].q.whereNull('provenTxId').whereNot({ status: 'completed' })
    qs[3].q.whereNot({ status: 'failed' })
  }

  for (let i = 0; i < qs.length; i++) {
    if (scope?.protectInputs && i === 1) continue
    await runReviewStatusQuery(qs[i])
  }

  return r
}

interface ReviewStatusQuery {
  q: Knex.QueryBuilder<any, number>
  sql?: string
  log: string
}

/** Real SQL primary fences and metadata keysets make each financial repair
 * independent of total wallet size. No external observation runs in a writer.
 * Explicit transaction/older-provider callers retain their serialized path. */
export async function reviewStatus(storage: StorageKnex, args: StorageStatusReviewArgs): Promise<{ log: string }> {
  if (args.trx != null || !(await storage.supportsPrimaryWriteFences())) return await reviewStatusLegacy(storage, args)
  let log = ''
  let afterUser = 0
  const admit: StorageWriterAdmission = args.admission ?? (async operation => await operation())
  for (;;) {
    const users: Array<{ userId: number; identityKey: string }> = await storage
      .knex('users')
      .select('userId', 'identityKey')
      .where('userId', '>', afterUser)
      .orderBy('userId')
      .limit(100)
    if (!users.length) break
    for (const user of users) {
      afterUser = user.userId
      try {
        const write = await storage.activeWriteTransaction(user)
        let afterTransaction = 0
        for (;;) {
          const ids: Array<{ transactionId: number }> = await storage
            .knex('transactions')
            .select('transactionId')
            .where({ userId: user.userId })
            .where('transactionId', '>', afterTransaction)
            .orderBy('transactionId')
            .limit(100)
          if (!ids.length) break
          for (const { transactionId } of ids) {
            const rows = await storage.findTransactions({
              partial: { transactionId, userId: user.userId },
              noRawTx: true
            })
            const row = rows[0]
            if (row == null) {
              afterTransaction = transactionId
              continue
            }
            if (row.status === 'failed' && row.txid != null) {
              const proven = (await storage.findProvenTxs({ partial: { txid: row.txid } }))[0]
              const req = await EntityProvenTxReq.fromStorageTxid(storage, row.txid)
              if (proven != null && req != null) {
                const writes = await StorageReqWrite.capture(
                  storage,
                  [row.txid],
                  { userId: user.userId, write },
                  args.admission
                )
                await storage.updateProvenTxReqWithNewProvenTx(
                  {
                    provenTxReqId: req.id,
                    txid: req.txid,
                    status: req.status,
                    attempts: req.attempts,
                    history: req.apiHistory,
                    height: proven.height,
                    index: proven.index,
                    blockHash: proven.blockHash,
                    merkleRoot: proven.merkleRoot,
                    merklePath: proven.merklePath
                  },
                  proven,
                  writes
                )
              }
            }
            log += await admit(
              async () =>
                await write.transaction(async trx => {
                  const current = (
                    await storage.findTransactions({
                      partial: { transactionId, userId: user.userId },
                      noRawTx: true,
                      trx
                    })
                  )[0]
                  if (current == null) return ''
                  const req =
                    current.txid == null
                      ? undefined
                      : await EntityProvenTxReq.fromStorageTxid(storage, current.txid, trx)
                  if (req?.status === 'unmined' && ['nosend', 'unprocessed', 'sending'].includes(current.status))
                    await storage.updateTransactionStatus('unproven', transactionId, user.userId, undefined, trx)
                  const protectedTargets =
                    current.txid == null
                      ? []
                      : await storage.findTransactions({
                          partial: { userId: user.userId, noSendExpiryReclaimTxid: current.txid },
                          noRawTx: true,
                          trx
                        })
                  const repaired = await reviewStatusLegacy(
                    storage,
                    { ...args, trx },
                    {
                      userId: user.userId,
                      transactionId,
                      protectInputs: protectedTargets.length > 0
                    }
                  )
                  if (req != null) await quarantineRecordedTerminalInputs(req, storage, user.userId, trx)
                  return repaired.log
                })
            )
            afterTransaction = transactionId
          }
        }
      } catch (error) {
        if (WalletError.fromUnknown(error).code !== 'WERR_NOT_ACTIVE') throw error
        log += `user ${user.userId} review deferred to its current primary\n`
      }
    }
  }
  return { log }
}
