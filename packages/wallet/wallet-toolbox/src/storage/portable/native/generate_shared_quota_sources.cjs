'use strict'

// Deterministic source-data generation only. No SQLite/native engine, owner,
// publication, executable pin or qualification is supplied by these bytes.
const fs = require('node:fs/promises')
const path = require('node:path')

async function generate() {
  if (process.argv.length !== 3 || !['--check', '--write'].includes(process.argv[2]))
    throw new Error('Expected only --check or --write')
  const root = path.resolve(__dirname, '../../../..')
  const journal = path.join(root, 'out/src/storage/snapshot/journal')
  const { nativeQuotaSources, nativeQuotaDispatchTriggers, nativeQuotaDispatchDdl } = require(
    path.join(journal, 'SnapshotJournalNativeQuotaSql.js')
  )
  const factories = [
    ['SnapshotJournalDestinationWindow', 'snapshotJournalDestinationWindowDdl'],
    ['SnapshotJournalDestinationStage', 'snapshotJournalDestinationStageDdl'],
    ['SnapshotJournalDestinationPromotion', 'snapshotJournalDestinationPromotionDdl'],
    ['SnapshotJournalCapturedIdentities', 'snapshotJournalCapturedIdentitiesDdl'],
    ['SnapshotJournalIdentityLedger', 'snapshotJournalIdentityLedgerDdl'],
    ['SnapshotJournalIdentityRetirements', 'snapshotJournalIdentityRetirementsDdl'],
    ['SnapshotJournalMemberships', 'snapshotJournalMembershipDdl'],
    ['SnapshotJournalProvenance', 'snapshotJournalProvenanceDdl'],
    ['SnapshotJournalProgress', 'snapshotJournalProgressDdl']
  ]
  // Pure DDL factories inspect only this dialect configuration; it is source
  // generation DATA, never a structurally supplied native Knex admission.
  const config = { client: { config: { client: 'better-sqlite3' } } }
  const ddl = factories.flatMap(([module, factory]) => require(path.join(journal, module + '.js'))[factory](config))
  const sources = nativeQuotaSources(ddl)
  const triggers = nativeQuotaDispatchTriggers(ddl)
  if (sources.length !== 18 || triggers.length !== 54 || nativeQuotaDispatchDdl.length !== 2)
    throw new Error('Original quota source inventory differs')
  const literal = value => JSON.stringify(value)
  const text =
    '// Generated by generate_shared_quota_sources.cjs; do not edit.\n' +
    'static const struct { const char *table, *sql; } brc38QuotaSources[] = {\n' +
    sources.map(source => '  {' + [source.table, source.sql].map(literal).join(',') + '}').join(',\n') +
    '\n};\n' +
    'static const struct { const char *table, *name, *sql; } brc38QuotaEmitters[] = {\n' +
    triggers
      .map(trigger => '  {' + [trigger.table, trigger.name, trigger.sql].map(literal).join(',') + '}')
      .join(',\n') +
    '\n};\n' +
    'static const char *brc38QuotaDispatchDefinitions[] = {\n' +
    nativeQuotaDispatchDdl.map(sql => '  ' + literal(sql)).join(',\n') +
    '\n};\n'
  const output = path.join(__dirname, 'shared_quota_sources.h')
  if (process.argv[2] === '--check') {
    if ((await fs.readFile(output, 'utf8')) !== text) throw new Error('Generated quota sources differ')
  } else {
    try {
      const actual = await fs.lstat(output)
      if (!actual.isFile() || actual.isSymbolicLink() || actual.nlink !== 1)
        throw new Error('Generated source target differs')
    } catch (error) {
      if (error.code !== 'ENOENT') throw error
    }
    await fs.writeFile(output, text, { mode: 0o644 })
  }
}
generate().catch(error => {
  console.error(String(error.message))
  process.exitCode = 1
})
